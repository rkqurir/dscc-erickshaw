/** WCAG 2.1 contrast helpers, used to warn when a zone plate colour cannot carry white letters (Schedule 3). */

function channel(c: number): number {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

export function relativeLuminance(hex: string): number {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex);
  if (!m) throw new Error('invalid colour');
  const n = parseInt(m[1], 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
}

export function contrastRatio(a: string, b: string): number {
  const la = relativeLuminance(a);
  const lb = relativeLuminance(b);
  const [hi, lo] = la > lb ? [la, lb] : [lb, la];
  return (hi + 0.05) / (lo + 0.05);
}

/** Plates carry white letters; 4.5:1 is the WCAG AA threshold for normal text. */
export function whiteTextContrastOk(background: string): boolean {
  return contrastRatio('#FFFFFF', background) >= 4.5;
}
